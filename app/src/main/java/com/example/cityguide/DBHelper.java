    private void insertPlace(SQLiteDatabase db, String name, String city, String category, String description, String imageName)
    {
        ContentValues values = new ContentValues();
        values.put(COLUMN_NAME, name);
        values.put("city", city);
        values.put(COLUMN_CATEGORY, category);
        values.put(COLUMN_DESCRIPTION, description);
        values.put(COLUMN_IMAGE, imageName);
        values.put(COLUMN_FAVORITE, 0);
        db.insert(TABLE_NAME, null, values);
    }

    public ArrayList<Place> getPlacesByCategory(String category, String city)
    {
        ArrayList<Place> list = new ArrayList<>();
        SQLiteDatabase db = this.getReadableDatabase();

        Cursor cursor = db.query(TABLE_NAME, null, COLUMN_CATEGORY + "=? AND city=?",
                new String[]{category, city}, null, null, null);


        if (cursor.moveToFirst()) {
            do {
                String name = cursor.getString(cursor.getColumnIndexOrThrow(COLUMN_NAME));
                String desc = cursor.getString(cursor.getColumnIndexOrThrow(COLUMN_DESCRIPTION));
                String imageName = cursor.getString(cursor.getColumnIndexOrThrow(COLUMN_IMAGE));
                int favoriteValue = cursor.getInt(cursor.getColumnIndexOrThrow(COLUMN_FAVORITE));
                boolean isFavorite = favoriteValue == 1;
                list.add(new Place(name, category, desc, imageName, isFavorite));
            } while (cursor.moveToNext());
        }

        cursor.close();
        return list;
    }

    public ArrayList<Place> getFavorites() {
        ArrayList<Place> list = new ArrayList<>();
        SQLiteDatabase db = this.getReadableDatabase();

        Cursor cursor = db.query(TABLE_NAME, null, COLUMN_FAVORITE + "=?",
                new String[]{"1"}, null, null, null);

        if (cursor.moveToFirst()) {
            do {
                String name = cursor.getString(cursor.getColumnIndexOrThrow(COLUMN_NAME));
                String category = cursor.getString(cursor.getColumnIndexOrThrow(COLUMN_CATEGORY));
                String desc = cursor.getString(cursor.getColumnIndexOrThrow(COLUMN_DESCRIPTION));
                String imageName = cursor.getString(cursor.getColumnIndexOrThrow(COLUMN_IMAGE));
                boolean isFavorite = true;
                list.add(new Place(name, category, desc, imageName, isFavorite));
            } while (cursor.moveToNext());
        }

        cursor.close();
        return list;
    }

    public void setFavorite(String name, boolean isFavorite) {
        SQLiteDatabase db = this.getWritableDatabase();
        ContentValues values = new ContentValues();
        values.put(COLUMN_FAVORITE, isFavorite ? 1 : 0);
        int updated = db.update(TABLE_NAME, values, COLUMN_NAME + "=?", new String[]{name});
        db.close();
    }

